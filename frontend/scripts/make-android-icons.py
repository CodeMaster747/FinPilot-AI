"""Draws the FinPilot AI launcher icons and splash screens into the Android project.

    .venv/bin/python frontend/scripts/make-android-icons.py

The mark is the one the web app uses: a white "circle check" (lucide's circle-check, 24-unit grid) on brand blue.
Android 8+ (every phone this app supports, minSdk 26) uses the adaptive icon, whose foreground is a vector drawable;
the PNGs are the legacy fallbacks. Needs Pillow (already a backend dependency).
"""

from __future__ import annotations

from pathlib import Path

from PIL import Image, ImageDraw

RES = Path(__file__).resolve().parents[1] / "android" / "app" / "src" / "main" / "res"
BLUE = (0x1F, 0x5F, 0xB4, 255)
WHITE = (255, 255, 255, 255)
PAGE = (0xF6, 0xF6, 0xF3, 255)
SS = 4  # supersampling factor for smooth edges

DENSITIES = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}


def draw_check(d: ImageDraw.ImageDraw, cx: float, cy: float, size: float, color=WHITE) -> None:
    """lucide circle-check scaled so its 24-unit grid spans `size` pixels, centred on (cx, cy)."""
    u = size / 24
    ox, oy = cx - 12 * u, cy - 12 * u
    w = 2 * u
    r = 10 * u
    d.ellipse([ox + 12 * u - r - w / 2, oy + 12 * u - r - w / 2, ox + 12 * u + r + w / 2, oy + 12 * u + r + w / 2], outline=color, width=round(w))
    pts = [(ox + 9 * u, oy + 12 * u), (ox + 11 * u, oy + 14 * u), (ox + 15 * u, oy + 10 * u)]
    d.line(pts, fill=color, width=round(w), joint="curve")
    for x, y in (pts[0], pts[-1]):  # round caps
        d.ellipse([x - w / 2, y - w / 2, x + w / 2, y + w / 2], fill=color)


def render(px: int, paint) -> Image.Image:
    big = Image.new("RGBA", (px * SS, px * SS), (0, 0, 0, 0))
    paint(ImageDraw.Draw(big), px * SS)
    return big.resize((px, px), Image.LANCZOS)


def legacy_icons() -> None:
    for name, scale in DENSITIES.items():
        folder = RES / f"mipmap-{name}"
        folder.mkdir(exist_ok=True)
        px = round(48 * scale)

        def square(d, s):
            m = s * 0.08
            d.rounded_rectangle([m, m, s - m, s - m], radius=s * 0.22, fill=BLUE)
            draw_check(d, s / 2, s / 2, s * 0.56)

        def circle(d, s):
            m = s * 0.04
            d.ellipse([m, m, s - m, s - m], fill=BLUE)
            draw_check(d, s / 2, s / 2, s * 0.56)

        render(px, square).save(folder / "ic_launcher.png")
        render(px, circle).save(folder / "ic_launcher_round.png")
        fg = round(108 * scale)
        render(fg, lambda d, s: draw_check(d, s / 2, s / 2, s * 0.5)).save(folder / "ic_launcher_foreground.png")


FOREGROUND_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- FinPilot AI mark (lucide circle-check) for the adaptive and themed launcher icon. Generated by
     frontend/scripts/make-android-icons.py. 108dp canvas; the 24-unit glyph is scaled to 54dp, inside the 66dp safe zone. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:translateX="27"
        android:translateY="27"
        android:scaleX="2.25"
        android:scaleY="2.25">
        <path
            android:pathData="M2,12a10,10 0,1 0,20 0a10,10 0,1 0,-20 0"
            android:strokeColor="#FFFFFFFF"
            android:strokeWidth="2"
            android:fillColor="#00000000" />
        <path
            android:pathData="M9,12l2,2l4,-4"
            android:strokeColor="#FFFFFFFF"
            android:strokeWidth="2"
            android:strokeLineCap="round"
            android:strokeLineJoin="round"
            android:fillColor="#00000000" />
    </group>
</vector>
"""

ADAPTIVE_XML = """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
    <monochrome android:drawable="@drawable/ic_launcher_foreground"/>
</adaptive-icon>
"""

BACKGROUND_XML = """<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="ic_launcher_background">#1F5FB4</color>
</resources>
"""


def adaptive_icon() -> None:
    # drawable-v24 holds the template's Android-robot foreground; it would win over drawable/ on every supported phone.
    for folder in ("drawable", "drawable-v24"):
        (RES / folder).mkdir(exist_ok=True)
        (RES / folder / "ic_launcher_foreground.xml").write_text(FOREGROUND_XML)
    for name in ("ic_launcher.xml", "ic_launcher_round.xml"):
        (RES / "mipmap-anydpi-v26" / name).write_text(ADAPTIVE_XML)
    (RES / "values" / "ic_launcher_background.xml").write_text(BACKGROUND_XML)


def splashes() -> None:
    """Pre-Android-12 launch background: the mark centred on the app's page colour (Android 12+ shows the icon itself)."""
    for path in RES.glob("drawable*/splash.png"):
        w, h = Image.open(path).size
        img = Image.new("RGBA", (w * SS, h * SS), PAGE)
        d = ImageDraw.Draw(img)
        s = min(w, h) * SS * 0.2
        cx, cy = w * SS / 2, h * SS / 2
        d.rounded_rectangle([cx - s / 2, cy - s / 2, cx + s / 2, cy + s / 2], radius=s * 0.22, fill=BLUE)
        draw_check(d, cx, cy, s * 0.56)
        img.resize((w, h), Image.LANCZOS).convert("RGB").save(path)


if __name__ == "__main__":
    legacy_icons()
    adaptive_icon()
    splashes()
    print(f"Icons and splash screens written under {RES}")
